public class Bit_Manipulation{
    public static void main(String args[]){
        System.out.println("Bitwaise AND : " + (6 & 7));
        System.out.println("Bitwaise OR  : " + (7 | 5));
        System.out.println("Bitwaise XOR : " + (5 ^ 6));
        System.out.println("Bitwaise 1's Complement : " + (~5));
        System.out.println("Bitwaise Left Shift : " + (9 << 2));
        System.out.println("Bitwaise Right Shift : " + (9 >> 1));
    }
}